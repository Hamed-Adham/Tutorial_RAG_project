class ScienceGenerator:
    """
    Generator for the 180+ item full-curriculum science benchmark across 15 chapters.
    """

    def __init__(self, grounder: TextbookGrounder = None, seed: int = 42):
        self.grounder = grounder or TextbookGrounder()
        self.seed = seed
        random.seed(seed)

    def generate_all(self) -> List[BenchmarkItemModel]:
        items: List[BenchmarkItemModel] = []

        # Generate 12 items per chapter for all 15 chapters = 180 items
        for ch in range(1, 16):
            items.extend(self._generate_chapter_items(ch))

        # Assign 75% dev / 25% test deterministically
        self._assign_splits(items)

        return items

    def _assign_splits(self, items: List[BenchmarkItemModel]):
        rng = random.Random(self.seed)
        shuffled = list(range(len(items)))
        rng.shuffle(shuffled)
        test_count = int(len(items) * 0.25)
        test_indices = set(shuffled[:test_count])

        for idx, item in enumerate(items):
            item.metadata.split = "test" if idx in test_indices else "dev"

    def _generate_chapter_items(self, chapter_num: int) -> List[BenchmarkItemModel]:
        """Generate 12 grounded items for a single chapter."""
        sections = self.grounder.get_sections(chapter_num)
        if not sections:
            return []

        pdf_name = Path(sections[0].source_pdf).name
        cat_title = CHAPTER_TITLES.get(chapter_num, f"فصل {chapter_num}")
        items: List[BenchmarkItemModel] = []

        # Predefined curriculum templates per chapter (5 Factoids, 3 Reasoning, 2 Diagrams, 2 Experiments)
        templates = self._get_chapter_templates(chapter_num, pdf_name)

        for idx, (q, a, q_type, pages, is_multi) in enumerate(templates, start=1):
            chunks = [f"{pdf_name}#page={p}" for p in pages]
            item_id = f"SCI-CH{chapter_num:02d}-{q_type[:4].upper()}-{idx:02d}"
            item = BenchmarkItemModel(
                id=item_id,
                input=q,
                expected_output=a,
                metadata=BenchmarkMetadataModel(
                    suite="science_textbook",
                    split="dev",
                    category=cat_title,
                    query_type=q_type,
                    ground_truth_doc_ids=[f"CH{chapter_num:02d}-SEC-{idx:04d}"],
                    ground_truth_chunks=chunks,
                    expected_behavior="answer",
                    expected_route="science_textbook",
                    requires_multi_hop=is_multi,
                )
            )
            items.append(item)

        return items

