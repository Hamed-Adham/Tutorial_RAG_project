def export_science_suite_csv(output_path: Path) -> List[BenchmarkItemModel]:
    """Generates all 180 science items and saves to 3-column CSV."""
    generator = ScienceGenerator()
    items = generator.generate_all()

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["input", "expected_output", "metadata"])
        for item in items:
            writer.writerow([
                item.input,
                item.expected_output,
                json.dumps(item.metadata.model_dump(), ensure_ascii=False)
            ])

    return items
